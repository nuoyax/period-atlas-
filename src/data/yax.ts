/**
 * 纵轴量程：一张图一条轴。
 *
 * 每条曲线给出它自己的物理量、单位与上下限；曲线形状仍是 0–1 的相对高度，
 * 显示时按本条的 lo–hi 线性映射回真实量。凡是真正复合、没有单一物理量的曲线，
 * 就老实写成「指数」，而不是假装成血压或体温那样的实测量。
 *
 * 所以横轴各画各的周期、纵轴各用各的量纲：这是一组小图，不是一个共享坐标系。
 */
export interface YAxis {
  /** 物理量名，如「收缩压」「月面照亮比例」 */
  q: string;
  /** 单位（含前导空格，如 " mmHg"），无量纲则为空串 */
  u: string;
  lo: number;
  hi: number;
  /** 小数位；缺省时按量程自动推断 */
  d?: number;
  /** 特殊映射：不是线性插值，而是由 0–1 高度直接给出真实值 */
  v?: (a: number) => number;
}

