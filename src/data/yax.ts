export const DEF_Y: YAxis = { q: "指数", u: "", lo: 0, hi: 100 };

export const yaxOf = (s: SeriesDef): YAxis => YAX[s.name] || DEF_Y;

/* 0–1 的相对高度 → 本条自己的量纲 */
export function yv(s: SeriesDef, a: number | null | undefined): string {
  if (a === null || a === undefined) return "—";
  const y = yaxOf(s);
  const v = y.v ? y.v(a) : (y.lo + a * (y.hi - y.lo));
  const span = Math.abs(y.hi - y.lo);
  const d = y.d != null ? y.d : (span >= 100 ? 0 : (span >= 10 ? 1 : 2));
  return v.toFixed(d) + (y.u || "");
}

export const ynameOf = (s: SeriesDef): string => {
  const y = yaxOf(s);
  return y.q + (y.u ? "（" + (y.u.trim() || y.u) + "）" : "");
};
